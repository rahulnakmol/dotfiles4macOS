#!/usr/bin/env node
// Maintainer generator only. Committed shell/JXA files run without Node.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync,chmodSync,readdirSync,unlinkSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const dir=join(root,'raycast/.config/raycast/workspaces');
const scripts=join(root,'raycast/.config/raycast/scripts');
const catalog=JSON.parse(readFileSync(join(dir,'catalog.json'),'utf8'));
const check=process.argv.includes('--check');
const favorites=JSON.parse(readFileSync(join(dir,'favorites.json'),'utf8')).favorites;
assert.equal(catalog.focus.defaultMinutes,45);
const aliases=new Set(),keys=new Set(),outputs=new Map(),reference=[];
const quote=s=>`'${s.replaceAll("'", "'\\''")}'`;
const profile={type:'dropdown',placeholder:'Display (Auto)',optional:true,data:[{title:'Auto',value:'auto'},{title:'Laptop',value:'laptop'},{title:'Desk',value:'desk'}]};
const minutes={type:'dropdown',placeholder:'Duration (45 min)',optional:true,data:[{title:'45 min',value:'45'},{title:'30 min',value:'30'},{title:'25 min',value:'25'}]};
for(const v of catalog.variants){
 assert.ok(!keys.has(v.hotkey),v.hotkey);keys.add(v.hotkey);
 for(const [action,prefix] of [['workspace','Workspace'],['layout','Arrange'],['focus','Focus']]){
  const alias=v.aliases[action];assert.match(alias,/^[a-z0-9]{3}$/);assert.ok(!aliases.has(alias),alias);aliases.add(alias);
  const filename=`native-${action}-${v.id}.sh`;
  const args=action==='focus'?[minutes,profile]:[profile];
  const source=['#!/bin/bash','# Generated by scripts/build-raycast-native.mjs; edit catalog.json/shared runtime.',
   '# @raycast.schemaVersion 1',`# @raycast.title ${prefix}: ${v.title}`,'# @raycast.mode compact',
   '# @raycast.packageName Native Workspaces','# @raycast.icon 🗂️',
   `# @raycast.description ${action==='focus'?'Prepare workspace, then confirm a 45-minute focus timer.':action==='workspace'?'Apply DockFlow and request the native layout. No timer.':'Request only the native layout. No DockFlow or timer change.'}`,
   ...args.map((a,i)=>`# @raycast.argument${i+1} ${JSON.stringify(a)}`),
   'set -euo pipefail','package="$(cd -- "$(dirname -- "$0")/../workspaces" && pwd)"',
   action==='focus'?`exec /bin/bash "$package/run.sh" focus ${quote(v.id)} "\${1:-45}" "\${2:-auto}"`:
    `exec /bin/bash "$package/run.sh" ${action} ${quote(v.id)} 45 "\${1:-auto}"`,''
  ].join('\n');
  outputs.set(join(scripts,filename),source);
  reference.push({title:`${prefix}: ${v.title}`,action,variant:v.id,alias,hotkey:action==='workspace'?v.hotkey:null,script:filename,status:'native_assignment_required'});
 }
}
assert.equal(new Set(favorites.map(f=>f.title)).size,favorites.length,'Duplicate favorite title');
const favoriteAliases=favorites.map(f=>f.alias).filter(Boolean);
assert.equal(new Set(favoriteAliases).size,favoriteAliases.length,'Duplicate favorite alias');
assert.ok(favorites.length<=10,'Keep at most ten favorites');
for(const f of favorites){
 if(f.alias!==null)assert.match(f.alias,/^[a-z0-9]{2,3}$/);
 if(f.title.startsWith('Workspace:')||f.title.startsWith('Focus:'))assert.ok(reference.some(r=>r.title===f.title&&r.alias===f.alias),`Unknown workflow favorite ${f.title}`);
}
const nativeLayouts=catalog.variants.flatMap(v=>['laptop','desk'].map(profile=>({
 name:`${v.title} | ${profile==='desk'?'Desk':'Laptop'}`,
 variant:v.id,profile,alias:v.aliases.layout+(profile==='desk'?'d':'l'),
 status:'native_assignment_required'
})));
for(const layout of nativeLayouts){assert.match(layout.alias,/^l[a-z0-9]{3}$/);assert.ok(!aliases.has(layout.alias));aliases.add(layout.alias);}
outputs.set(join(dir,'reference.json'),JSON.stringify({version:1,focusDefaultMinutes:45,assignments:reference,nativeLayouts,favorites},null,2)+'\n');
outputs.set(join(dir,'quicklinks.json'),JSON.stringify([{name:'Mobbin — Latest Web Apps',link:'https://mobbin.com/discover/apps/web/latest',openWith:'Zen'}],null,2)+'\n');
if(!check){mkdirSync(scripts,{recursive:true});for(const f of readdirSync(scripts))if(/^native-(workspace|layout|focus)-/.test(f)&&!outputs.has(join(scripts,f)))unlinkSync(join(scripts,f));}
for(const [path,source] of outputs){if(check)assert.equal(readFileSync(path,'utf8'),source,`Regenerate ${path}`);else{writeFileSync(path,source);if(path.endsWith('.sh'))chmodSync(path,0o755);}}
console.log(`${check?'Checked':'Generated'} ${reference.length} native Script Commands; ${keys.size} workspace keys; 45-minute Focus default.`);
