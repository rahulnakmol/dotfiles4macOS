#!/usr/bin/env node
import assert from 'node:assert/strict';
import { chmodSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const configDir = join(root, 'raycast/.config/raycast/launchers');
const scriptDir = join(root, 'raycast/.config/raycast/scripts');
const config = JSON.parse(readFileSync(join(configDir, 'config.json'), 'utf8'));
const check = process.argv.includes('--check');
assert.deepEqual(config.sessionMinutes, [25, 30, 45]);
assert.equal(config.defaultSessionMinutes, 45);
assert.equal(config.quicklinkAliasLeader, 'q');
assert.equal(new Set(config.sessionCategories.map(c => c.name)).size, config.sessionCategories.length);
assert.equal(new Set(config.dockflowPresets.map(p => p.name)).size, config.dockflowPresets.length);

function save(path, text, executable = false) {
  if (check) {
    assert.equal(readFileSync(path, 'utf8'), text, `Regenerate ${path}`);
    return;
  }
  writeFileSync(path, text);
  if (executable) chmodSync(path, 0o755);
}
function shellQuote(value) {
  return `'${value.replaceAll("'", "'\\''")}'`;
}
if (!check) {
  mkdirSync(configDir, { recursive: true });
  mkdirSync(scriptDir, { recursive: true });
}

const quicklinks = [];
const reference = { observedDate: config.observedDate, aliasUpdatedDate: config.aliasUpdatedDate, quicklinkAliasLeader: config.quicklinkAliasLeader, defaultSessionMinutes: config.defaultSessionMinutes, sessions: [], dockflow: [] };
const categoryNames=config.sessionCategories.map(c=>c.name);
const categoryArg={type:'dropdown',placeholder:'Category (Work)',optional:true,data:categoryNames.map(name=>({title:name,value:name}))};
const minutesArg={type:'dropdown',placeholder:'Minutes (45)',optional:true,data:[45,30,25].map(value=>({title:`${value} min`,value:String(value)}))};
const sessionScript=`#!/bin/bash
# Generated by scripts/build-raycast-launchers.mjs; edit launchers/config.json.
# @raycast.schemaVersion 1
# @raycast.title ${config.sessionCommand.name}
# @raycast.mode silent
# @raycast.packageName Session Focus
# @raycast.icon ⏱️
# @raycast.description Start one Session timer with a category and duration; default 45 minutes.
# @raycast.argument1 ${JSON.stringify(categoryArg)}
# @raycast.argument2 ${JSON.stringify(minutesArg)}
set -euo pipefail
category="\${1:-Work}"
minutes="\${2:-45}"
case "$category" in ${categoryNames.map(shellQuote).join('|')}) ;; *) printf 'Unknown Session category\\n' >&2; exit 2 ;; esac
case "$minutes" in 25|30|45) ;; *) printf 'Minutes must be 25, 30 or 45\\n' >&2; exit 2 ;; esac
url="session:///start?categoryName=$category&duration=$minutes"
if [[ "\${3:-}" == --preview ]]; then printf '%s\\n' "$url"; exit 0; fi
session_app="$(/usr/bin/osascript -l JavaScript <<'JXA'
ObjC.import('AppKit');
var ids=['com.philipyoungg.session-setapp','com.philipyoungg.session'];
var found='';
for(var i=0;i<ids.length;i++){var u=$.NSWorkspace.sharedWorkspace.URLForApplicationWithBundleIdentifier(ids[i]);if(!u.isNil()){found=ObjC.unwrap(u.path);break;}}
if(!found)throw new Error('Session is not installed.');
found;
JXA
)"
exec /usr/bin/open -a "$session_app" "$url"
`;
save(join(scriptDir,'start-focus-session.sh'),sessionScript,true);
reference.sessions.push({name:config.sessionCommand.name,alias:config.sessionCommand.alias,kind:'script-command',script:'~/.dotfiles/raycast/.config/raycast/scripts/start-focus-session.sh',categories:categoryNames,minutes:config.sessionMinutes,defaultMinutes:config.defaultSessionMinutes,hotkey:null});

for (const preset of config.dockflowPresets) {
  const label = preset.name.replace(/^\d+\.\s*/, '');
  const name = `DockFlow: ${label}`;
  const filename = `dockflow-${preset.key}-${label.toLowerCase()}.sh`;
  const script = `#!/bin/bash
# Generated by scripts/build-raycast-launchers.mjs; edit launchers/config.json.
# @raycast.schemaVersion 1
# @raycast.title ${name}
# @raycast.mode silent
# @raycast.packageName DockFlow Presets
# @raycast.icon 🧰
# @raycast.description Apply the existing ${preset.name} DockFlow preset.

set -euo pipefail
cli=${shellQuote(config.dockflowCLI)}
if [[ ! -x "$cli" ]]; then
  printf 'DockFlow CLI is missing: %s\\n' "$cli" >&2
  exit 1
fi
exec "$cli" apply --name ${shellQuote(preset.name)} --skip-if-active
`;
  save(join(scriptDir, filename), script, true);
  reference.dockflow.push({ name, preset: preset.name, observedId: preset.id, alias: `d${preset.key}`, hotkey: `control+option+${preset.key}`, script: `~/.dotfiles/raycast/.config/raycast/scripts/${filename}`, kind: 'script-command' });
}

assert.ok(reference.sessions.every(s => /^q[a-z]{2}$/.test(s.alias)));
const aliases = [...reference.sessions, ...reference.dockflow].map(x => x.alias);
assert.equal(aliases.length, new Set(aliases).size);
assert.ok(aliases.every(x => /^[a-z0-9]{2,4}$/.test(x)));
const keys = [...reference.sessions, ...reference.dockflow].flatMap(x => x.hotkey ? [x.hotkey] : []);
assert.equal(keys.length, new Set(keys).size);
save(join(configDir, 'session-quicklinks.json'), JSON.stringify(quicklinks, null, 2) + '\n');
save(join(configDir, 'reference.json'), JSON.stringify(reference, null, 2) + '\n');
console.log(`${check ? 'Checked' : 'Generated'} ${reference.sessions.length} Session Script Command and ${reference.dockflow.length} DockFlow Script Commands.`);
